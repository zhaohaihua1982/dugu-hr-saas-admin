-- 业务参考: docs/系统管理-登录配置设计.md §3.1
-- 迁移幂等：CREATE TABLE IF NOT EXISTS，启动时执行（单语句文件——迁移器每文件整体 Exec）。
CREATE TABLE IF NOT EXISTS `sys_login_config` (
    `id`                    BIGINT       NOT NULL COMMENT '雪花ID（seed 固定 9200 段）',
    `config_type`           TINYINT      NOT NULL COMMENT '1管理后台登录 2租户登录',
    `scope_id`              BIGINT       NOT NULL DEFAULT 0 COMMENT '0=全局；预留按租户覆盖',
    `login_mask`            BIGINT       NOT NULL COMMENT '登录组件位掩码：1账号密码 2手机密码 4手机短信 8邮箱密码（位只增不改）',
    `fail_threshold`        SMALLINT     NOT NULL DEFAULT 5 COMMENT '错误登录次数阈值 3~20',
    `lock_minutes`          SMALLINT     NOT NULL DEFAULT 15 COMMENT '冻结时长（分钟）1~1440',
    `unlock_mode`           TINYINT      NOT NULL DEFAULT 3 COMMENT '1自动到期 2仅管理员 3两者皆可',
    `captcha_after_fails`   SMALLINT     NOT NULL DEFAULT 3 COMMENT 'N次失败后强制图形码，0=关闭',
    `ip_fail_limit`         SMALLINT     NOT NULL DEFAULT 50 COMMENT '单IP登录失败限流（次/小时）',
    `ip_rate_limit`         SMALLINT     NOT NULL DEFAULT 20 COMMENT '单IP登录请求限流（次/分钟）',
    `access_token_ttl`      INT          NOT NULL DEFAULT 7200 COMMENT 'accessToken有效期（秒）',
    `refresh_token_ttl`     INT          NOT NULL DEFAULT 604800 COMMENT 'refreshToken有效期（秒）',
    `session_hard_ttl`      INT          NOT NULL DEFAULT 86400 COMMENT '会话硬上限（秒）',
    `session_max_concurrent` SMALLINT    NOT NULL DEFAULT 3 COMMENT '同账号最大并发会话，0=不限',
    `kick_on_pwd_change`    TINYINT(1)   NOT NULL DEFAULT 1 COMMENT '修改密码是否踢下线',
    `remember_days`         SMALLINT     NOT NULL DEFAULT 0 COMMENT '记住登录状态天数，0=关闭',
    `pwd_level`             TINYINT      NOT NULL DEFAULT 2 COMMENT '密码复杂度等级：1低 2中 3高（仅预设展示，明细为唯一真相）',
    `pwd_min_length`        SMALLINT     NOT NULL DEFAULT 10 COMMENT '最小密码长度 8~32',
    `pwd_min_classes`       SMALLINT     NOT NULL DEFAULT 2 COMMENT '最少字符类别数 1~4',
    `pwd_forbid_username`   TINYINT(1)   NOT NULL DEFAULT 1 COMMENT '禁止包含账号名',
    `pwd_max_age_days`      INT          NOT NULL DEFAULT 0 COMMENT '密码有效期（天），0=不过期',
    `pwd_expire_action`     TINYINT      NOT NULL DEFAULT 1 COMMENT '1到期提示 2到期强制改密',
    `pwd_remind_days`       SMALLINT     NOT NULL DEFAULT 7 COMMENT '到期提前提醒天数',
    `pwd_history_count`     SMALLINT     NOT NULL DEFAULT 3 COMMENT '不得与最近N次密码重复，0=不限制',
    `pwd_force_first_change` TINYINT(1)  NOT NULL DEFAULT 0 COMMENT '首次登录强制改密（重置密码后置位用户标记）',
    `allow_self_change_pwd` TINYINT(1)   NOT NULL DEFAULT 1 COMMENT '允许自助改密',
    `extras`                JSON         NULL COMMENT '扩展项：mfa_mode/ip_whitelist 等（未知 key 保留不删）',
    `version`               INT          NOT NULL DEFAULT 0 COMMENT '乐观锁',
    `updated_by`            BIGINT       NOT NULL DEFAULT 0 COMMENT '最后修改人（审计）',
    `created_at`            DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    `updated_at`            DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    PRIMARY KEY (`id`),
    UNIQUE KEY `uk_config` (`config_type`, `scope_id`)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_0900_ai_ci;
